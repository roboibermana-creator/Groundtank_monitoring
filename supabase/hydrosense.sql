-- ============================================================
-- Tabel
-- ============================================================
create table if not exists public.hs_sensor_readings (
  id                bigint generated by default as identity primary key,
  "timestamp"       timestamptz not null default now(),
  ph                numeric,
  tss               numeric,
  water_temperature numeric,
  water_level       numeric,
  tss_raw           numeric
);

create table if not exists public.hs_water_level_readings (
  id          bigint generated always as identity primary key,
  "timestamp" timestamptz not null default now(),
  water_level numeric not null check (water_level >= 0 and water_level <= 100),
  distance_cm numeric
);
create index if not exists water_level_readings_timestamp_idx
  on public.hs_water_level_readings ("timestamp" desc);

create table if not exists public.hs_calibration_samples (
  id           bigserial primary key,
  device_id    text not null,
  titik        text not null check (titik in ('ph4', 'ph7', 'ph10')),
  aksi         text not null check (aksi in ('kalibrasi', 'verifikasi')),
  sample_index integer not null check (sample_index >= 1 and sample_index <= 20),
  ph           numeric not null,
  suhu         numeric not null,
  mv           numeric,
  created_at   timestamptz not null default now()
);
create index if not exists idx_calibration_samples_created_at
  on public.hs_calibration_samples (created_at desc);
create index if not exists idx_calibration_samples_lookup
  on public.hs_calibration_samples (device_id, titik, aksi, sample_index);

create table if not exists public.hs_tss_calibration_samples (
  id           bigserial primary key,
  device_id    text not null,
  standard     text not null check (standard in ('std_a', 'std_b', 'std_c')),
  aksi         text not null check (aksi in ('kalibrasi', 'verifikasi')),
  sample_index integer not null check (sample_index >= 1 and sample_index <= 20),
  tss          numeric not null,
  suhu         numeric not null,
  ntu          numeric,
  raw_value    numeric,
  created_at   timestamptz not null default now()
);

create table if not exists public.hs_tss_calibration_config (
  id           bigint generated by default as identity primary key,
  device_id    text,
  slope        numeric not null default 1,
  cal_offset   numeric not null default 0,
  source       text not null default 'regression' check (source in ('regression', 'manual')),
  points_count integer,
  created_at   timestamptz not null default now()
);

create table if not exists public.hs_tss_hw_calibration_cmd (
  id           bigint generated by default as identity primary key,
  device_id    text,
  perintah     text not null check (perintah in (
                 'cek_status', 'siapkan', 'set_titik1', 'tulis_titik1',
                 'set_titik2', 'tulis_titik2', 'verifikasi_keluar', 'reset_factor')),
  nilai_target numeric,
  nilai_aktual numeric,
  status       text not null default 'pending' check (status in ('pending', 'sukses', 'gagal')),
  pesan        text,
  reg13        integer,
  reg14        integer,
  diproses_at  timestamptz,
  created_at   timestamptz not null default now()
);

create table if not exists public.hs_system_control (
  id         bigint generated always as identity primary key,
  device_id  text not null,
  mode       text not null default 'otomatis',
  valve_cmd  text not null default 'tutup',
  pump_cmd   text not null default 'berhenti',
  wiper_cmd  text not null default 'diam',
  updated_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create table if not exists public.hs_device_status (
  device_id  text primary key,
  pump_on    boolean not null default false,
  pump_note  text not null default 'berhenti',
  updated_at timestamptz not null default now()
);

-- ============================================================
-- Trigger: isi diproses_at saat status berubah dari 'pending'
-- ============================================================
create or replace function public.hs_set_tss_hw_calibration_diproses_at()
returns trigger language plpgsql as $$
begin
  if new.status is distinct from old.status and new.status <> 'pending' then
    new.diproses_at = now();
  end if;
  return new;
end;
$$;

drop trigger if exists trg_hs_set_tss_hw_calibration_diproses_at on public.hs_tss_hw_calibration_cmd;
create trigger trg_hs_set_tss_hw_calibration_diproses_at
  before update on public.hs_tss_hw_calibration_cmd
  for each row execute function public.hs_set_tss_hw_calibration_diproses_at();

-- ============================================================
-- RLS: baca + tambah publik (sama dengan project lama);
-- update hanya untuk hs_tss_hw_calibration_cmd dan hs_device_status.
-- ============================================================
do $$
declare
  t text;
begin
  -- tabel yang hanya perlu baca + tambah
  foreach t in array array[
    'hs_sensor_readings', 'hs_water_level_readings', 'hs_calibration_samples',
    'hs_tss_calibration_samples', 'hs_tss_calibration_config', 'hs_system_control'
  ] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists %I on public.%I', t || '_read', t);
    execute format('drop policy if exists %I on public.%I', t || '_insert', t);
    execute format('create policy %I on public.%I for select to anon, authenticated using (true)', t || '_read', t);
    execute format('create policy %I on public.%I for insert to anon, authenticated with check (true)', t || '_insert', t);
  end loop;

  -- tabel yang juga perlu update
  foreach t in array array['hs_tss_hw_calibration_cmd', 'hs_device_status'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists %I on public.%I', t || '_read', t);
    execute format('drop policy if exists %I on public.%I', t || '_insert', t);
    execute format('drop policy if exists %I on public.%I', t || '_update', t);
    execute format('create policy %I on public.%I for select to anon, authenticated using (true)', t || '_read', t);
    execute format('create policy %I on public.%I for insert to anon, authenticated with check (true)', t || '_insert', t);
    execute format('create policy %I on public.%I for update to anon, authenticated using (true) with check (true)', t || '_update', t);
  end loop;
end $$;

-- ============================================================
-- Realtime: hs_system_control (perintah pompa/valve/wiper dari dashboard)
-- ============================================================
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'hs_system_control'
  ) then
    alter publication supabase_realtime add table public.hs_system_control;
  end if;
end $$;
